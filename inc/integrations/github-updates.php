<?php
/** Public GitHub Releases updates through WordPress's native theme updater. @package HerizonCars */
defined('ABSPATH') || exit;

add_filter('update_themes_github.com', 'herizon_cars_github_theme_update', 10, 4);

/**
 * Only this exact theme/Update URI pair belongs to this updater.
 *
 * Core compares versions and honours the administrator's automatic-update choice.
 * This integration runs while Herizon Cars is active, including network activation.
 *
 * @param array|false $update Existing result from another provider.
 * @param array       $theme_data Theme headers supplied by WordPress.
 * @param string      $theme_stylesheet Theme directory name.
 * @param string[]    $locales Installed locales (no translation packages offered).
 * @return array|false
 */
function herizon_cars_github_theme_update($update, $theme_data, $theme_stylesheet, $locales)
{
    if ($update || $theme_stylesheet !== 'herizon-cars'
        || ($theme_data['UpdateURI'] ?? '') !== 'https://github.com/abel-hechavarria/herizon-cars') {
        return $update;
    }

    $cache_key = 'herizon_cars_github_release_v1';
    $cached = get_site_transient($cache_key);
    if (is_array($cached) && array_key_exists('update', $cached)) {
        return is_array($cached['update']) ? $cached['update'] : $update;
    }

    $response = wp_safe_remote_get('https://api.github.com/repos/abel-hechavarria/herizon-cars/releases/latest', [
        'timeout' => 8,
        'redirection' => 0,
        'limit_response_size' => 262144,
        'headers' => [
            'Accept' => 'application/vnd.github+json',
            'X-GitHub-Api-Version' => '2022-11-28',
        ],
    ]);

    $release_update = false;
    if (!is_wp_error($response) && wp_remote_retrieve_response_code($response) === 200) {
        $release = json_decode(wp_remote_retrieve_body($response), true, 32);
        if (is_array($release)) {
            $release_update = herizon_cars_github_release_update($release);
        }
    }

    // Cache failures too: a missing release, outage or rate limit must not hammer GitHub.
    set_site_transient($cache_key, ['update' => $release_update], $release_update ? HOUR_IN_SECONDS : 5 * MINUTE_IN_SECONDS);
    return $release_update ?: $update;
}

/**
 * Validate untrusted API data against the fixed repository and ZIP contract.
 *
 * Requirements come from the strict release-body marker generated by our workflow.
 * GitHub source archives are deliberately not installation packages.
 *
 * @return array|false Native WordPress theme update fields.
 */
function herizon_cars_github_release_update(array $release)
{
    $tag = $release['tag_name'] ?? null;
    if (!is_string($tag) || strlen($tag) > 50
        || !preg_match('/\Av((?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*))\z/', $tag, $matches)
        || ($release['draft'] ?? null) !== false || ($release['prerelease'] ?? null) !== false) {
        return false;
    }

    $version = $matches[1];
    $release_url = 'https://github.com/abel-hechavarria/herizon-cars/releases/tag/' . $tag;
    if (($release['html_url'] ?? '') !== $release_url || !is_array($release['assets'] ?? null)) {
        return false;
    }

    $body = $release['body'] ?? null;
    if (!is_string($body) || substr_count($body, '<!-- herizon-cars-update') !== 1
        || !preg_match('/<!-- herizon-cars-update (\{[^\r\n]*\}) -->/', $body, $metadata_match)) {
        return false;
    }
    $requirements = json_decode($metadata_match[1], true, 4);
    if (!is_array($requirements) || count($requirements) !== 2) {
        return false;
    }
    foreach (['requires', 'requires_php'] as $key) {
        if (!is_string($requirements[$key] ?? null) || strlen($requirements[$key]) > 20
            || !preg_match('/\A(?:0|[1-9][0-9]*)(?:\.(?:0|[1-9][0-9]*)){1,2}\z/', $requirements[$key])) {
            return false;
        }
    }

    $filename = 'herizon-cars-' . $version . '.zip';
    $package = 'https://github.com/abel-hechavarria/herizon-cars/releases/download/' . $tag . '/' . $filename;
    foreach ($release['assets'] as $asset) {
        if (!is_array($asset) || ($asset['name'] ?? '') !== $filename
            || ($asset['state'] ?? '') !== 'uploaded' || ($asset['browser_download_url'] ?? '') !== $package
            || !is_int($asset['size'] ?? null) || $asset['size'] <= 0) {
            continue;
        }

        return [
            'theme' => 'herizon-cars',
            'version' => $version,
            'url' => $release_url,
            'package' => $package,
            'requires' => $requirements['requires'],
            'requires_php' => $requirements['requires_php'],
        ];
    }

    return false;
}
